#!/bin/bash

echo "🚀 Starting deep clean of your workspace..."

# 1. JavaScript Junk: node_modules, .next, .turbo, dist
# 2. Python Junk: venv, .venv, __pycache__, .pytest_cache
# 3. Environment/Build Junk: .DS_Store (Mac), build/

find . -type d \( \
    -name "node_modules" -o \
    -name ".next" -o \
    -name "venv" -o \
    -name ".venv" -o \
    -name "__pycache__" -o \
    -name "build" -o \
    -name ".pytest_cache" \
\) -prune -exec rm -rf {} +

# Clean up individual system files (like Mac .DS_Store)
find . -type f -name ".DS_Store" -delete

echo "✅ Done! Your folders are now lean and ready for backup."
